/**
 * One identity as the editor **edits** it — plan §4.14, artboard S8.
 *
 * > **Parameter and state identities** are created from slot chips or the Identities list: name (a
 * > `symbol_instance` with indices), members, dtype, location. … **Locations** (parameter
 * > identities): a chooser over the four forms — from the `location` `oneOf` — each rendered from
 * > its schema … `stack`: axis (select of the slot's axis names plus `multiplicity` when the slot
 * > declares one — **names the core returns**), part (a nested location).
 *
 * Three questions a location editor asks, and none of them is a component's to answer:
 *
 * | Question | Answered by |
 * |---|---|
 * | which axes a `stack`, a `concat` or a `slice` may name | the slot's shape **as stored** ({@link storageShape}), which is what `evaluate_location` resolves an axis against |
 * | what an `{index}` and a `{coordinate}` token may name | the index environment the rule fires in, and the same stored axes |
 * | what the names evaluate to, instance by instance | `evaluate_location`'s own answer, which the bindings stage already computed and D3 writes |
 *
 * **The preview is D3's own value, one step before D3.** §4.14 asks for "the evaluated names for
 * the current preview index … from D3 when fresh, else from the core's evaluation"; the two are
 * one value — `TensorInstance.location` is `evaluate_location`'s answer, D3 copies it into the
 * derived document, and V17 checks it — so the preview reads the analysis rather than the
 * derivation. It is the fresher of the two (the analysis is recomputed on every keystroke, a
 * derivation follows a passing validation) and it is never a second evaluator.
 *
 * **What is not here.** The refusals: V17's lines are `analyse`'s and land in Problems with their
 * pointers (§4.17), and a location editor that restated them would be a second implementation of
 * a rule. And the verdict on a candidate — a tensor dragged from the Weights panel, a slot joining
 * an identity — which is {@link checkCandidate}'s, on that one candidate.
 */
